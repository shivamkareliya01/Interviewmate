export function getAllBankQuestions(): BankQuestion[] {
  const custom = getSavedCustomBankQuestions();
  const baseIds = new Set(PRACTICE_QUESTION_BANK.map((q) => q.id));
  const uniqueCustom = custom.filter((q) => !baseIds.has(q.id));
  const allCurrent = [...PRACTICE_QUESTION_BANK, ...uniqueCustom];

  // Track existing domains in the pool
  const existingDomains = new Set(allCurrent.map((q) => q.domain.toLowerCase().trim()));

  // Dynamically seed baseline questions for any domain in DOMAINS_BY_BRANCH that has no questions yet
  const dynamicSeeds: BankQuestion[] = [];
  Object.values(DOMAINS_BY_BRANCH).forEach((domainList) => {
    domainList.forEach((d) => {
      if (!existingDomains.has(d.name.toLowerCase().trim())) {
        existingDomains.add(d.name.toLowerCase().trim());
        dynamicSeeds.push(...generateBaselineForDomain(d.name, d.description));
      }
    });
  });

  return [...allCurrent, ...dynamicSeeds];
}
