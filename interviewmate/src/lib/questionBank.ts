const LOCAL_STORAGE_CUSTOM_BANK_KEY = "interviewmate_custom_question_bank";

export function getSavedCustomBankQuestions(): BankQuestion[] {
  if (typeof window === "undefined") return [];
  try {
    const raw = localStorage.getItem(LOCAL_STORAGE_CUSTOM_BANK_KEY);
    return raw ? JSON.parse(raw) : [];
  } catch {
    return [];
  }
}

export function saveQuestionsToBank(newQuestions: BankQuestion[]): void {
  if (typeof window === "undefined" || !newQuestions || newQuestions.length === 0) return;
  try {
    const existing = getSavedCustomBankQuestions();
    const existingIds = new Set(existing.map((q) => q.id));
    const toAdd = newQuestions.filter((q) => !existingIds.has(q.id));

    if (toAdd.length > 0) {
      const updated = [...existing, ...toAdd];
      localStorage.setItem(LOCAL_STORAGE_CUSTOM_BANK_KEY, JSON.stringify(updated));
    }
  } catch (err) {
    console.error("Failed to save generated questions to bank store:", err);
  }
}

